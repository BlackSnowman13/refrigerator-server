/** Option for dropdown (value sent to controller, label shown in UI) */
export interface RegisterOption {
  value: number;
  label: string;
}

export interface RegisterInfo {
  code: string;
  register: number;
  description: string;
  access: 'R' | 'R/W';
  type: 'Analog' | 'Digital' | 'Integer';
  /** If set, register appears in Config page under this section. */
  configSection?: 'eev' | 'pressure-s1' | 'pressure-s3' | 'temperature-s2' | 'temperature-s4' | 'refrigeration' | 'local-controls';
  /** Dropdown options; when set, UI uses select instead of number input. */
  options?: RegisterOption[];
  /** Two-level dropdown: first select group (e.g. Ratiometric vs Current), then option. Stored value is the option value. */
  optionGroups?: { groupLabel: string; groupValue: string; options: RegisterOption[] }[];
  /** Min value for number input (inclusive). */
  min?: number;
  /** Max value for number input (inclusive). */
  max?: number;
  /** Register code to use for dynamic min (e.g. 'P04' for P03 max = P04 value). */
  minRef?: string;
  /** Register code to use for dynamic max (e.g. 'P03' for P04 min = P03 value). */
  maxRef?: string;
  /** Unit suffix shown next to input (e.g. "%", "s", "steps", "pps"). */
  unit?: string;
  /** If true, register is not shown in Config UI (e.g. F10). */
  hidden?: boolean;
}

